# 取款机取钱的过程，假定你的密码是：123456，账户余额为1000
# 1．提示用户输入密码
psw = input('请输入密码：')
# 2．判断密码是否正确
if psw == '123456':
    # 3. 密码正确后，提示输入取款的金额
    money = int(input('登录成功，请输入取款金额:'))
    if (money <= 1000) and money > 0:
        print(f'{money}元正在结算，请等待。')
    elif money > 1000:
        print(f'您的卡内余额仅1000元，不足{money}元，无法提取。')
    else:
        print('输入金额无效，请重试！')
# 4. 判断取款的金额和余额的关系
else:
    print('密码错误')


